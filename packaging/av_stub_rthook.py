"""Runtime-hook: подменяет PyAV заглушкой в собранном приложении (T-318).

Зачем. Колёса PyAV несут собственную сборку FFmpeg, а в ней `libx264` и
`libx265` — кодеки под GPLv2+. GPL-компонент в поставке распространяет GPL на
всю поставку, и MIT-лицензия самого приложения этого не отменяет. Поэтому `av`
внесён в `excludes` спеки, и его DLL в сборку не попадают.

Почему нельзя ограничиться `excludes`. `faster_whisper/__init__.py` первой
строкой тянет `decode_audio`, а `faster_whisper/audio.py` делает `import av` на
уровне модуля. Без пакета `av` падает импорт всего faster-whisper — то есть
приложение целиком, ещё до первой транскрипции.

Что делает хук. Кладёт в `sys.modules` модуль-пустышку с именем `av`. Импорт
проходит, а любое обращение к атрибуту даёт понятную ошибку вместо
`AttributeError` из недр библиотеки. Приложение декодированием файлов не
занимается: и диктовка, и запись созвона отдают модели numpy-массив, читая wav
штатным `wave` из стандартной библиотеки. Единственный вызов, который передавал
путь к файлу, переведён на массив в этой же задаче.

Хук исполняется **только в замороженной сборке**. Запуск из исходников и
батч-CLI расшифровок (`~/.claude/scripts/transcribe.py`, читает `.oga`/`.mp3`)
работают с настоящим PyAV, установленным как зависимость faster-whisper.
"""

import sys
import types

_MESSAGE = (
    "Эта сборка собрана без PyAV/FFmpeg: их готовые бинарники распространяются "
    "под GPL. Декодирование аудио-файлов недоступно — приложение работает с "
    "записью напрямую (wav + numpy)."
)


class _AVStub(types.ModuleType):
    """Модуль, который существует ровно настолько, чтобы пройти импорт."""

    __version__ = "0-stub"

    def __getattr__(self, name: str):
        # Служебные атрибуты (`__path__`, `__all__`, `__wrapped__`) спрашивает
        # не наш код, а машинерия импорта и `inspect`. На них полагается
        # отвечать AttributeError — это штатный способ сказать «такого нет».
        # Пока здесь на любое имя летел RuntimeError, `import faster_whisper`
        # падал ещё до первой строки нашего кода.
        if name.startswith("__") and name.endswith("__"):
            raise AttributeError(name)
        raise RuntimeError(f"{_MESSAGE} (запрошено av.{name})")


if "av" not in sys.modules:
    sys.modules["av"] = _AVStub("av")
